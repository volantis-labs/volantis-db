#!/usr/bin/env python3
"""Reference-loader token oracle for the WF-986 e5 pair (offline).

IDs come from `SentenceTransformer.tokenize`, the loader that reference.py uses:
it strips each prompted input (Python `str.strip`), then runs tokenizer.json with
HF tokenizers 0.19.1 and right truncation at each tower's PAIR.json limit.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess

os.environ["HF_HUB_OFFLINE"] = "1"
os.environ["TRANSFORMERS_OFFLINE"] = "1"

import tokenizers
import xxhash

SOURCES = {
    "query": "c206f3d926756214f88ca52ce7d934c946bdaea2949c8d3c17d806e15b39a82c",
    "document": "0b44a9d7b51c3c62626640cda0e2c2f70fdacdc25bbbd68038369d14ebdf4c39",
}
PAIR_SHA256 = "782b0a40e43fb9d83b2f647dea33289024fab79e5320fb19042764669f8e0a98"
TEXTS_SHA256 = "523ba4b66c0afd6cafbfdcdceb79a64a1b697a8b6b9edca4e64c2014de05d999"
# The same raw text goes through both roles. Repeat counts keep long rows compact.
CASES = [
    ("en", "Where is the nearest train station? The bronze zeppelin lands at noon.", 1),
    ("de", "Wo ist der nächste Bahnhof? Grüße aus Köln, die Straße ist schön.", 1),
    ("fr", "Où est la gare la plus proche ? L'été à Noël, déjà vu.", 1),
    ("nl", "Waar is het dichtstbijzijnde station? De fiets staat bij de brug.", 1),
    ("empty", "", 1),
    ("repeated_spaces", "one  two   three    four", 1),
    ("trailing_space", "trail ", 1),
    ("single_space", " ", 1),
    ("leading_spaces", "  lead", 1),
    ("literal_metaspace", "one▁two ▁three", 1),
    ("special_inside", "a<mask>b", 1),
    ("special_spaced", "a <mask> b", 1),
    ("adjacent_specials", "<s></s><pad><unk>x", 1),
    ("combining", "Café ạ́ ȫ Glühbirne", 1),
    ("whitespace", "  one\t\t two\n\nthree\r\n four five  ", 1),
    ("controls", "a\u0001b\u0000c‍d", 1),
    ("emoji_zwj", "😀 👩🏽‍💻 👨‍👩‍👧‍👦 🏳️‍🌈", 1),
    ("full_width", "ＡＢＣ１２３　ｶﾀｶﾅ Å ① ﬃ ²", 1),
    ("unknown", "𐀀𐀁hello𐀀", 1),
    ("python_space_edges", "\u001c\u3000 edge \t\u001f", 1),
]


def rust_string(text):
    literal = json.dumps(text, ensure_ascii=False)
    return re.sub(r"\\u([0-9a-fA-F]{4})", lambda m: "\\u{" + m[1] + "}", literal)


def pinned(pack, name, expected):
    path = pack / name
    if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
        raise ValueError(f"{name} SHA256 differs from the pinned WF-986 source")
    return path


def boundary(loader, prefix, word, limit):
    """Smallest repeat count of `word` that fills the limit exactly, then one more."""
    length = lambda count: len(loader.tokenizer((prefix + word * count).strip())["input_ids"])
    count = 1
    while length(count) < limit:
        count += 1
    if length(count) != limit:
        raise ValueError(f"{word!r} cannot fill {limit} tokens exactly")
    return [(f"exact_{limit}", word, count), (f"over_{limit}", word, count + 1)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pack", type=Path, required=True)
    parser.add_argument("--rust-out", type=Path, required=True)
    args = parser.parse_args()
    from sentence_transformers import SentenceTransformer, __version__ as st_version

    if tokenizers.__version__ != "0.19.1" or st_version != "3.0.1":
        raise ValueError("the WF-986 oracle requires tokenizers 0.19.1, sentence-transformers 3.0.1")
    pair = json.loads(pinned(args.pack, "PAIR.json", PAIR_SHA256).read_text())
    texts_path = pinned(args.pack, "fixtures/texts.json", TEXTS_SHA256)
    texts = json.loads(texts_path.read_text())["texts"]
    lines = ["// Generated by tools/ze-model/e5-pair-tokenizer-goldens.py: SentenceTransformer",
             "// 3.0.1 tokenize (Python strip, then HF tokenizers 0.19.1 on tokenizer.json).",
             "// Limits follow PAIR.json and include the prefix and both boundary tokens.",
             f'pub const PAIR_SHA256: &str = "{PAIR_SHA256}";',
             f'pub const TEXTS_SHA256: &str = "{TEXTS_SHA256}";',
             f"pub const TEXTS_XXH3: u64 = {xxhash.xxh3_64_intdigest(texts_path.read_bytes())};",
             "pub const TEXTS: &[&str] = &["]
    lines += [f"    {rust_string(text)}," for text in texts]
    lines.append("];")
    for role in ["query", "document"]:
        record = pair[role]
        path = pinned(args.pack, f"{record['path']}/tokenizer.json", SOURCES[role])
        loader = SentenceTransformer(str(path.parent), device="cpu", local_files_only=True)
        prefix, limit = record["prefix"], int(record["max_tokens"])
        loader.max_seq_length = limit
        cases = CASES + [(f"texts_{i}", text, 1) for i, text in enumerate(texts)]
        cases += boundary(loader, prefix, "the ", limit)
        upper = role.upper()
        lines += [f'pub const {upper}_SHA256: &str = "{SOURCES[role]}";',
                  f"pub const {upper}_PREFIX: &str = {rust_string(prefix)};",
                  f"pub const {upper}_MAX_TOKENS: usize = {limit};",
                  f"pub const {upper}_CASES: &[(&str, &str, usize, &[i32])] = &["]
        for name, text, repeat in cases:
            encoded = loader.tokenize([prefix + text * repeat])
            ids = encoded["input_ids"][0].tolist()
            assert encoded["attention_mask"][0].tolist() == [1] * len(ids)
            assert not name.startswith(("exact_", "over_")) or len(ids) == limit
            lines.append(f"    ({rust_string(name)}, {rust_string(text)}, {repeat}, &{ids}),")
        lines.append("];")
    args.rust_out.write_text("\n".join(lines) + "\n")
    subprocess.run(["rustfmt", "--edition", "2024", str(args.rust_out)], check=True)


if __name__ == "__main__":
    main()
